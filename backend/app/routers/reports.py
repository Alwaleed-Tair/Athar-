def _pick(table, key, ar):
    pair = table.get(key)
    return (pair[1] if ar else pair[0]) if pair else key


def _fmt_ts(ts: str | None) -> str:
    return (ts or "").replace("T", " ")[:19] or "—"


def _fmt_size(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return str(n)


def _gather(conn, user: dict, case_id: int, lang: str) -> dict:
    ar = lang == "ar"
    t = T[lang]
    case = conn.execute(
        "SELECT c.*, COALESCE(NULLIF(u.full_name,''), u.username) AS owner_name FROM cases c "
        "JOIN users u ON u.id = c.created_by WHERE c.id = ?", (case_id,)).fetchone()
    ev_rows = conn.execute(
        "SELECT e.*, COALESCE(NULLIF(u.full_name,''), u.username) AS uploader FROM evidence e "
        "JOIN users u ON u.id = e.uploaded_by WHERE e.case_id = ? AND e.deleted_at IS NULL "
        "ORDER BY e.uploaded_at", (case_id,)).fetchall()

    items = []
    for r in ev_rows:
        result, actual = integrity.check_file(r)
        try:
            exif = json.loads(r["exif_json"] or "{}")
        except ValueError:
            exif = {}
        make, model = exif.get("Make"), exif.get("Model")
        is_image = Path(r["filename"]).suffix.lower() in {".jpg", ".jpeg", ".png", ".tiff", ".tif", ".webp", ".bmp", ".heic", ".heif"}
        ind = analysis.check_exif_authenticity_indicators(exif) if is_image else None
        conv = chats.get_meta(conn, r["id"])
        an = conn.execute("SELECT result_json, analyzed_at FROM evidence_analysis WHERE evidence_id = ?", (r["id"],)).fetchone()
        au = conn.execute("SELECT result_json FROM evidence_authenticity WHERE evidence_id = ?", (r["id"],)).fetchone()
        items.append({
            "row": r, "integrity": result, "actual": actual, "exif": exif, "is_image": is_image, "ind": ind,
            "device": f"{make or ''} {model or ''}".strip() or None,
            "capture": exif.get("DateTime"), "software": exif.get("Software"),
            "conv": conv, "stats": chats.compute_stats(conn, r["id"]) if conv else None,
            "analysis": json.loads(an["result_json"]) if an else None,
            "auth": json.loads(au["result_json"]) if au else None,
        })

    rels = relations.compute_relations(conn, user["id"], case_id)
    same = [x for x in rels if x["same_case"]]
    seen, rel_rows = set(), []
    for x in same:
        k = tuple(sorted((x["evidence_id"], x["other_evidence_id"])))
        if k in seen:
            continue
        seen.add(k)
        rel_rows.append(x)

    chain = audit.verify_chain(case_id=case_id)
    log_rows = conn.execute("SELECT * FROM audit_log WHERE case_id = ? ORDER BY seq", (case_id,)).fetchall()
    summ = conn.execute("SELECT summary_text, generated_at FROM case_summary WHERE case_id = ?", (case_id,)).fetchone()
    return {"case": case, "items": items, "relations": rel_rows, "chain": chain, "log": log_rows, "summary": summ}


def build_report(conn, user: dict, case_id: int, lang: str) -> tuple[bytes, dict]:
    lang = lang if lang in T else "en"
    ar = lang == "ar"
    t = T[lang]
    d = _gather(conn, user, case_id, lang)
    case, items = d["case"], d["items"]
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")

    fp_src = json.dumps({
        "case": case["id"], "evidence": [(i["row"]["id"], i["row"]["sha256"], i["integrity"]) for i in items],
        "chain": d["chain"], "log_count": len(d["log"]),
    }, sort_keys=True)
    fingerprint = hashlib.sha256(fp_src.encode()).hexdigest()

    bad_files = [i for i in items if i["integrity"] != "MATCH"]
    dup_pairs = [r for r in d["relations"] if any(x["type"] == "IDENTICAL_FILE" for x in r["reasons"])]
    edit_imgs = [i for i in items if i["ind"] and i["ind"]["editing_software_detected"]]
    nometa = [i for i in items if i["ind"] and i["ind"]["missing_camera_metadata"]]
    convs = [i for i in items if i["conv"]]

    def render(total):
        p = Pdf(ar, f"{t['footer']}  |  {case['case_identifier'] or 'CASE-%04d' % case['id']}", total)
        p.title_block(t["title"], f"{t['sub']}   |   {case['name']}")
        data_tag = (t["tag_data"], GREEN, GREEN_BG)
        ai_tag = (t["tag_ai"], AMBER, AMBER_BG)
        mix_tag = (t["tag_mix"], GREEN, GREEN_BG)

        # 1 case info
        p.h1(t["case_info"], data_tag)
        p.kv(t["case_name"], case["name"])
        p.kv(t["case_id"], case["case_identifier"] or "CASE-%04d" % case["id"])
        p.kv(t["status"], _pick(STATUS, case["status"], ar))
        p.kv(t["priority"], _pick(PRIORITY, case["priority"], ar))
        p.kv(t["classification"], _pick(CLASS, case["classification"], ar))
        p.kv(t["owner"], case["owner_name"])
        p.kv(t["created"], _fmt_ts(case["created_at"]))
        if case["description"]:
            p.kv(t["desc"], case["description"])
        p.kv(t["generated"], generated)
        p.kv(t["generated_by"], user.get("full_name") or user["username"])
        p.kv(t["fingerprint"], fingerprint)
        p.spacer(4)

        # 2 executive summary (deterministic)
        p.h1(t["exec"], mix_tag)
        if items:
            cats = {}
            for i in items:
                cats[i["row"]["category"]] = cats.get(i["row"]["category"], 0) + 1
            cat_txt = "، ".join(f"{i18n.CATEGORY_LABELS.get(k, {}).get('ar' if ar else 'en', k)} ({v})" for k, v in cats.items()) if ar \
                else ", ".join(f"{i18n.CATEGORY_LABELS.get(k, {}).get('en', k)} ({v})" for k, v in cats.items())
            p.bullet(t["exec_counts"].format(n=len(items), cats=cat_txt))
            p.bullet(t["exec_integrity_ok"].format(n=len(items)) if not bad_files
                     else t["exec_integrity_bad"].format(bad=len(bad_files), n=len(items)))
        else:
            p.bullet(t["no_evidence"])
        p.bullet(t["exec_chain_ok"].format(n=d["chain"]["records_checked"]) if d["chain"]["intact"]
                 else t["exec_chain_bad"].format(seq=d["chain"]["first_broken_seq"]))
        p.bullet(t["exec_links"].format(n=len(d["relations"])))
        if convs:
            p.bullet(t["exec_convs"].format(n=len(convs), m=sum(i["conv"]["message_count"] for i in convs)))
        flags = []
        if dup_pairs: flags.append(t["flag_dup"].format(n=len(dup_pairs)))
        if edit_imgs: flags.append(t["flag_edit"].format(n=len(edit_imgs)))
        if nometa: flags.append(t["flag_nometa"].format(n=len(nometa)))
        if bad_files: flags.append(t["mismatch"])
        p.bullet(t["exec_flags"].format(flags=("؛ " if ar else "; ").join(flags)) if flags else t["exec_noflags"])
        if d["summary"]:
            p.bullet(t["exec_ai"])
        p.spacer(4)

        # 3 inventory
        p.h1(t["evidence_list"], data_tag)
        if not items:
            p.para(t["no_evidence"])
        else:
            rows = []
            for n, i in enumerate(items, 1):
                r = i["row"]
                rows.append([str(n), (r["title"] + " - " if r["title"] else "") + r["filename"],
                             i18n.CATEGORY_LABELS.get(r["category"], {}).get("ar" if ar else "en", r["category"]),
                             _fmt_size(r["size_bytes"]), _fmt_ts(r["uploaded_at"]), r["uploader"] or t["uploader_unknown"]])
            p.table(["#", t["name"], t["category"], t["size"], t["uploaded"], t["by"]], rows,
                    [0.05, 0.33, 0.15, 0.1, 0.22, 0.15])
            for n, i in enumerate(items, 1):
                if i["row"]["description"]:
                    p.para(f"[{n}] {i['row']['description']}", size=8.6, color=GREY)

        # 4 integrity
        p.h1(t["integrity"], mix_tag)
        rows = []
        for n, i in enumerate(items, 1):
            res = {"MATCH": t["match"], "MISMATCH": t["mismatch"], "MISSING": t["missing"]}[i["integrity"]]
            rows.append([str(n), i["row"]["sha256"], i["actual"] or "—", res])
        if rows:
            p.table(["#", t["hash"], t["live"], t["result"]], rows, [0.05, 0.36, 0.36, 0.23], size=6.6)
        if bad_files:
            p.callout(t["exec_integrity_bad"].format(bad=len(bad_files), n=len(items)), RED, RED_BG)
        if d["chain"]["intact"]:
            p.callout(f"{t['chain_ok']} ({d['chain']['records_checked']} {t['records']})", GREEN, GREEN_BG)
        else:
            p.callout(t["chain_bad"].format(seq=d["chain"]["first_broken_seq"]), RED, RED_BG)

        # 5 forensic
        p.h1(t["forensic"], data_tag)
        for n, i in enumerate(items, 1):
            p.h2(f"[{n}] {i['row']['title'] or i['row']['filename']}")
            if i["is_image"]:
                p.kv(t["device"], i["device"] or t["not_available"])
                p.kv(t["captured"], str(i["capture"] or t["not_available"]))
                p.kv(t["software"], str(i["software"] or t["none"]))
                if i["ind"]["editing_software_detected"]:
                    p.callout(t["editing"].format(sw=i["software"]), AMBER, AMBER_BG)
                elif i["ind"]["missing_camera_metadata"]:
                    p.para(t["exif_missing"], size=8.6, color=GREY)
            else:
                p.para(i["row"]["content_type"] or i["row"]["filename"].rsplit(".", 1)[-1].upper(), size=8.6, color=GREY)

        # 6 relations
        p.h1(t["links"], data_tag)
        if not d["relations"]:
            p.para(t["no_links"])
        label = {"IDENTICAL_FILE": t["identical"], "SAME_DEVICE": t["same_device"], "TEXT_SIMILARITY": t["text_sim"],
                 "SHARED_PARTICIPANT": t["participant"]}
        for r in d["relations"]:
            reasons = "؛ " if ar else "; "
            txt = reasons.join(f"{label.get(x['type'], t['shared'] + ' (' + x['type'].replace('SHARED_', '').lower() + ')')}: {x['value']}"
                               for x in r["reasons"])
            p.bullet(f"{r['evidence_name']}  <->  {r['other_evidence_name']}  -  {txt}")

        # 7 conversations
        p.h1(t["convs"], data_tag)
        if not convs:
            p.para(t["no_conv"])
        else:
            p.para(t["source_note"], size=8.6, color=GREY)
        for i in convs:
            c, s = i["conv"], i["stats"]
            p.h2(i["row"]["title"] or i["row"]["filename"])
            p.kv(t["format"], c["format"])
            p.kv(t["messages"], str(c["message_count"]))
            p.kv(t["participants"], "، ".join(f"{x['name']} ({x['messages']})" for x in c["participants"]) if ar
                 else ", ".join(f"{x['name']} ({x['messages']})" for x in c["participants"]))
            p.kv(t["range"], f"{_fmt_ts(c['first_ts'])}  →  {_fmt_ts(c['last_ts'])}" if c["first_ts"] else t["not_available"])
            if s["top_terms"]:
                p.kv(t["top_terms"], ", ".join(x["term"] for x in s["top_terms"][:10]))

        # 8 AI
        has_ai = bool(d["summary"]) or any(i["analysis"] or (i["auth"] and i["auth"].get("ai_assessment")) or
                                           (i["conv"] and i["conv"]["summary"]) for i in items)
        p.h1(t["ai"], ai_tag)
        if not has_ai:
            p.para(t["ai_none"])
        else:
            p.callout(t["ai_warn"], AMBER, AMBER_BG)
            if d["summary"]:
                p.h2(f"{t['ai_summary']}  ({_fmt_ts(d['summary']['generated_at'])})")
                p.para(d["summary"]["summary_text"], size=9)
            for i in items:
                name = i["row"]["title"] or i["row"]["filename"]
                a = i["analysis"]
                if a and a.get("status") == "SUCCESS":
                    p.h2(t["ai_item"].format(n=name))
                    if a.get("summary"):
                        p.para(a["summary"], size=9)
                    for cobj in a.get("correlations", [])[:8]:
                        p.bullet(f"{cobj.get('evidence_filename', '')}: {cobj.get('explanation', '')}", size=9)
                au = i["auth"]
                if au and au.get("ai_assessment"):
                    aa = au["ai_assessment"]
                    p.h2(f"{t['ai_auth']} - {name}")
                    p.para(f"{aa.get('label', '')}: {aa.get('explanation', '')}", size=9)
                cs = i["conv"]["summary"] if i["conv"] else None
                if cs and cs.get("status") == "SUCCESS":
                    p.h2(t["ai_conv"].format(n=name))
                    p.para(cs.get("summary", ""), size=9)
                    for k in cs.get("key_events", []):
                        p.bullet(f"{k['description']}  [#{', #'.join(str(x) for x in k['refs'])}]", size=9)

        # 9 custody
        p.h1(t["custody"], mix_tag)
        rows = []
        for r in d["log"][:300]:
            try:
                params = json.loads(r["params_json"])
            except ValueError:
                params = {}
            rows.append([str(r["seq"]), _fmt_ts(r["ts"]), i18n.build_message(r["action"], params, lang), r["event_hash"][:16]])
        p.table([t["seq"], t["time"], t["event"], "SHA-256"], rows, [0.07, 0.2, 0.55, 0.18], size=7.4)
        if len(d["log"]) > 300:
            p.para(f"… {len(d['log']) - 300} more", size=8, color=GREY)

        # 10 method
        p.h1(t["method"])
        for line in t["method_text"]:
            p.bullet(line, size=9)
        return p

    first = render(None)
    total_pages = first.page
    final = render(total_pages)
    meta = {"intact": d["chain"]["intact"], "evidence_count": len(items), "fingerprint": fingerprint,
            "case_name": case["name"], "identifier": case["case_identifier"] or "CASE-%04d" % case["id"]}
    return final.finish(), meta


