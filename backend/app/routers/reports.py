def case_report(case_id: int, user: dict = Depends(require_case_member), lang: str = Query(default="en")):
    with get_conn() as conn:
        pdf, meta = build_report(conn, user, case_id, lang)
    audit.append_event(
        "REPORT_GENERATED", actor_id=user["id"], case_id=case_id,
        params={"username": user["username"], "case_name": meta["case_name"],
                "evidence_count": meta["evidence_count"], "intact": meta["intact"],
                "fingerprint": meta["fingerprint"]},
    )
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d")
    return Response(
        content=pdf, media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="ATHAR-report-{meta["identifier"]}-{stamp}.pdf"',
                 "Cache-Control": "no-store"},
    )
